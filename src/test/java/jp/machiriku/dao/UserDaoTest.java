package jp.machiriku.dao;

import static org.junit.Assert.*;

import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Proxy;
import java.sql.Connection;
import java.sql.SQLException;

import org.junit.After;
import org.junit.Assume;
import org.junit.Before;
import org.junit.Test;

import jp.machiriku.bean.User;

/** 任意で実行するDB連携テスト。既存会員レコードや実テーブルの採番には書き込まない。 */
public class UserDaoTest {
    private Connection connection;
    private UserDao dao;

    @Before
    // 明示的に有効にした場合だけ、実DBの定義を使って接続中だけ有効なテスト用テーブルを作る。
    public void openTemporaryUsersTable() throws Exception {
        Assume.assumeTrue("true".equalsIgnoreCase(System.getenv("MACHIRIKU_RUN_DB_TESTS")));
        connection = Dao.getConnection();
        connection.setAutoCommit(false);
        try (var statement = connection.createStatement()) {
            // LIKEによる複製は実テーブルのSELECT権限を必要とするため、カタログ情報から定義を再構成する。
            // アプリ用ロールに会員テーブルの参照権限が未設定でも、既存レコードを読まずにテストできる。
            StringBuilder definition = new StringBuilder("CREATE TEMP TABLE users (");
            try (var columns = statement.executeQuery("SELECT a.attname, format_type(a.atttypid,a.atttypmod), "
                    + "a.attidentity, a.attnotnull, pg_get_expr(d.adbin,d.adrelid) "
                    + "FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum "
                    + "WHERE a.attrelid='public.users'::regclass AND a.attnum>0 AND NOT a.attisdropped ORDER BY a.attnum")) {
                while (columns.next()) {
                    if (definition.charAt(definition.length() - 1) != '(') { definition.append(", "); }
                    definition.append(quote(columns.getString(1))).append(' ').append(columns.getString(2));
                    String identity = columns.getString(3);
                    if (!identity.isEmpty()) {
                        definition.append(identity.equals("a") ? " GENERATED ALWAYS AS IDENTITY" : " GENERATED BY DEFAULT AS IDENTITY");
                    } else if (columns.getString(5) != null) {
                        definition.append(" DEFAULT ").append(columns.getString(5));
                    }
                    if (columns.getBoolean(4)) { definition.append(" NOT NULL"); }
                }
            }
            try (var constraints = statement.executeQuery("SELECT pg_get_constraintdef(oid) FROM pg_constraint "
                    + "WHERE conrelid='public.users'::regclass AND contype IN ('p','u','c') ORDER BY conname")) {
                while (constraints.next()) { definition.append(", ").append(constraints.getString(1)); }
            }
            // 利用区分更新のcommit後も一時表を保ち、接続を閉じたときに破棄する。
            statement.execute(definition.append(") ON COMMIT PRESERVE ROWS").toString());
            // 移行前の実DBでも、テスト対象は電話番号をプロフィールへ移した会員定義にそろえる。
            statement.execute("ALTER TABLE pg_temp.users DROP COLUMN IF EXISTS phone_e164 CASCADE");
            try (var rows = statement.executeQuery("SELECT 'users'::regclass::oid = 'pg_temp.users'::regclass::oid")) {
                assertTrue(rows.next());
                assertTrue("Unqualified users must resolve to the temporary table", rows.getBoolean(1));
            }
        }
        Connection borrowed = (Connection) Proxy.newProxyInstance(Connection.class.getClassLoader(),
                new Class<?>[]{Connection.class}, (proxy, method, args) -> {
                    if (method.getName().equals("close")) { return null; }
                    try { return method.invoke(connection, args); }
                    catch (InvocationTargetException e) { throw e.getCause(); }
                });
        dao = new UserDao() {
            @Override protected Connection openConnection() { return borrowed; }
        };
    }

    @After
    // テストの成功・失敗にかかわらず、変更をロールバックして接続を閉じる。
    public void rollbackAndClose() throws Exception {
        if (connection != null) {
            try { connection.rollback(); }
            finally { connection.close(); }
        }
    }

    @Test
    // 登録した会員情報とDBの初期値を確認し、LINE IDによる検索を検証する。
    public void savesRequestedFieldsAndReadsExistingLineSubject() throws Exception {
        User saved = dao.insert(registration("RESIDENT"));
        assertTrue(saved.getUserId() > 0);
        assertEquals("PENDING", saved.getAccountStatus());
        assertNotNull(saved.getCreatedAt());
        assertNotNull(saved.getUpdatedAt());
        User found = dao.findByLineSubject("test-line-subject");
        assertEquals(saved.getUserId(), found.getUserId());
        assertEquals("テスト表示名 <>&", found.getDisplayName());
        assertEquals("line-test@example.invalid", found.getEmail());
        assertEquals("RESIDENT", found.getUserRole());
        assertEquals("test-line-subject", found.getLineSubject());
        assertNull(dao.findByLineSubject("missing' OR '1'='1"));
    }

    @Test
    // 各利用区分が、電話番号のプロフィール登録前でもLINE会員を作成できることを確認する。
    public void everyPublicRoleCanCreatePendingUserBeforeProfileRegistration() throws Exception {
        for (String role : new String[] { "RESIDENT", "BUSINESS", "OWNER" }) {
            User registration = registration(role);
            registration.setLineSubject("pending-profile-" + role);
            registration.setEmail(null);
            User saved = dao.insert(registration);
            assertEquals(role, saved.getUserRole());
            assertEquals("PENDING", saved.getAccountStatus());
            assertNull(saved.getEmail());
        }
    }

    @Test
    // メール未取得や空白をNULLとして保存し、複数のLINE会員が登録できることを確認する。
    public void savesMissingAndBlankEmailsAsNullForMultipleLineAccounts() throws Exception {
        String[] missingEmails = { null, "", " \t " };
        for (int i = 0; i < missingEmails.length; i++) {
            User registration = registration("RESIDENT");
            registration.setLineSubject("no-email-line-subject-" + i);
            registration.setEmail(missingEmails[i]);
            User saved = dao.insert(registration);
            assertTrue(saved.getUserId() > 0);
            assertNull(saved.getEmail());
            assertNull(dao.findByLineSubject(registration.getLineSubject()).getEmail());
        }
    }

    @Test
    // 同じLINE IDの二重登録を、実際のDB制約で拒否できることを確認する。
    public void rejectsDuplicateLineSubjectUsingExistingDatabaseConstraint() throws Exception {
        dao.insert(registration("RESIDENT"));
        User duplicate = registration("RESIDENT");
        duplicate.setEmail("different@example.invalid");
        try { dao.insert(duplicate); fail("Duplicate subject must fail"); }
        catch (SQLException e) { assertEquals("23505", e.getSQLState()); }
    }

    @Test
    // 不正な利用区分・長すぎるメールを保存前に拒否することを確認する。
    public void rejectsInvalidRoleAndOverlongEmail() throws Exception {
        User invalidRole = registration("ADMIN");
        assertThrows(IllegalArgumentException.class, () -> dao.insert(invalidRole));
        User overlongEmail = registration("RESIDENT");
        overlongEmail.setEmail("a".repeat(255));
        assertThrows(IllegalArgumentException.class, () -> dao.insert(overlongEmail));
    }

    @Test
    // 本登録前は各区分を選び直せて、LINE本人情報と会員IDは維持されることを確認する。
    public void pendingUserCanReselectEachPublicRoleWhileKeepingIdentity() throws Exception {
        User original = dao.insert(registration("RESIDENT"));
        for (String role : new String[] { "BUSINESS", "OWNER", "RESIDENT" }) {
            User updated = dao.updatePendingRole(original.getLineSubject(), role);
            assertEquals(original.getUserId(), updated.getUserId());
            assertEquals(role, updated.getUserRole());
            assertEquals("PENDING", updated.getAccountStatus());
            assertEquals(original.getDisplayName(), updated.getDisplayName());
            assertEquals(original.getEmail(), updated.getEmail());
            assertEquals(original.getLineSubject(), updated.getLineSubject());
            assertEquals(original.getCreatedAt(), updated.getCreatedAt());
            assertEquals(role, dao.findByLineSubject(original.getLineSubject()).getUserRole());
        }
    }

    @Test
    // 本登録済み・停止・退会状態と、退会日時がある会員では利用区分が変更されない。
    public void completedBannedAndWithdrawnAccountsKeepTheirRoles() throws Exception {
        User original = dao.insert(registration("RESIDENT"));
        for (String status : new String[] { "ACTIVE", "BAN", "WITHDRAWN", "PENDING" }) {
            boolean withdrawn = "WITHDRAWN".equals(status) || "PENDING".equals(status);
            try (var statement = connection.prepareStatement(
                    "UPDATE pg_temp.users SET account_status=?,withdrawn_at=CASE WHEN ? THEN CURRENT_TIMESTAMP ELSE NULL END WHERE user_id=?")) {
                statement.setString(1, status);
                statement.setBoolean(2, withdrawn);
                statement.setInt(3, original.getUserId());
                statement.executeUpdate();
            }
            User updated = dao.updatePendingRole(original.getLineSubject(), "OWNER");
            assertEquals("RESIDENT", updated.getUserRole());
            assertEquals(status, updated.getAccountStatus());
            assertEquals(withdrawn, updated.getWithdrawnAt() != null);
            assertEquals("RESIDENT", dao.findByLineSubject(original.getLineSubject()).getUserRole());
        }
    }

    @Test
    // 存在しないLINE IDは新規会員を作らず、呼び出し元へ未登録を返す。
    public void unknownLineSubjectDoesNotCreateOrChangeUsers() throws Exception {
        User original = dao.insert(registration("RESIDENT"));
        assertNull(dao.updatePendingRole("missing' OR '1'='1", "OWNER"));
        assertEquals("RESIDENT", dao.findByLineSubject(original.getLineSubject()).getUserRole());
        assertNull(dao.findByLineSubject("missing' OR '1'='1"));
    }

    @Test
    // 公開登録で認めていない区分と、不正なLINE IDは更新前に拒否する。
    public void roleReselectionRejectsInvalidRoleOrLineSubject() throws Exception {
        User original = dao.insert(registration("RESIDENT"));
        for (String role : new String[] { null, "", "resident", "ADMIN", "OWNER' OR '1'='1" }) {
            assertThrows(IllegalArgumentException.class, () -> dao.updatePendingRole(original.getLineSubject(), role));
        }
        for (String subject : new String[] { null, "", " ", "a".repeat(256) }) {
            assertThrows(IllegalArgumentException.class, () -> dao.updatePendingRole(subject, "OWNER"));
        }
        assertEquals("RESIDENT", dao.findByLineSubject(original.getLineSubject()).getUserRole());
    }

    @Test
    // DB更新に失敗しても元の利用区分を保ち、借りた接続の設定を復元する。
    public void failedRoleUpdateRollsBackAndRestoresConnectionState() throws Exception {
        User original = dao.insert(registration("RESIDENT"));
        try (var statement = connection.createStatement()) {
            statement.execute("ALTER TABLE pg_temp.users ADD CONSTRAINT test_owner_block CHECK (user_role <> 'OWNER')");
        }
        connection.commit();
        SQLException error = assertThrows(SQLException.class, () -> dao.updatePendingRole(original.getLineSubject(), "OWNER"));
        assertEquals("23514", error.getSQLState());
        assertFalse(connection.getAutoCommit());
        assertEquals("RESIDENT", dao.findByLineSubject(original.getLineSubject()).getUserRole());
        assertEquals("PENDING", dao.findByLineSubject(original.getLineSubject()).getAccountStatus());
    }

    private User registration(String role) {
        User user = new User();
        user.setDisplayName("テスト表示名 <>&");
        user.setEmail("line-test@example.invalid");
        user.setUserRole(role);
        user.setLineSubject("test-line-subject");
        return user;
    }

    private String quote(String name) { return "\"" + name.replace("\"", "\"\"") + "\""; }
}

-- migrate-admin-management.sqlの後に、DB所有者としてこのファイルを1回実行する。
BEGIN;

-- 既存の主キーを保持したまま、管理画面から業種マスターを追加できるよう自動採番を設定する。
ALTER TABLE public.industry_categories ALTER COLUMN category_id ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE public.industry_types ALTER COLUMN industry_type_id ADD GENERATED BY DEFAULT AS IDENTITY;

-- 既に登録されている最大のIDの次から採番し、既存の利用区分・投票・要件との参照を保持する。
SELECT setval(pg_get_serial_sequence('public.industry_categories', 'category_id'), COALESCE(max(category_id), 0)::bigint + 1, false)
FROM public.industry_categories;
SELECT setval(pg_get_serial_sequence('public.industry_types', 'industry_type_id'), COALESCE(max(industry_type_id), 0)::bigint + 1, false)
FROM public.industry_types;

COMMENT ON SEQUENCE public.industry_categories_category_id_seq IS '管理画面で追加する業種カテゴリのIDを発行する。';
COMMENT ON SEQUENCE public.industry_types_industry_type_id_seq IS '管理画面で追加する業種のIDを発行する。';

-- 管理者が会員・物件と、その申込・投票・アンケートなどの履歴を照会できるようにする。
GRANT SELECT ON TABLE public.users, public.resident_profiles, public.business_profiles, public.owner_profiles,
    public.user_locations, public.user_industry_preferences, public.business_qualifications,
    public.industry_categories, public.industry_types, public.qualifications, public.industry_qualification_requirements,
    public.properties, public.property_contract_terms, public.property_industries, public.property_images,
    public.property_votes, public.vote_choices, public.applications, public.application_checks, public.tenancies,
    public.opening_plans, public.offers, public.surveys, public.survey_questions, public.survey_options,
    public.survey_responses, public.survey_answers, public.coupons, public.coupon_recipients
TO machiriku_app;

-- 各管理操作に必要な更新だけを許可し、管理権限の付与は引き続きDB所有者が行う。
GRANT UPDATE ON TABLE public.users, public.resident_profiles, public.business_profiles, public.owner_profiles,
    public.properties, public.opening_plans, public.coupons, public.coupon_recipients
TO machiriku_app;
GRANT INSERT, UPDATE ON TABLE public.user_locations, public.business_qualifications,
    public.industry_categories, public.industry_types, public.qualifications, public.surveys
TO machiriku_app;
GRANT INSERT, DELETE ON TABLE public.user_industry_preferences TO machiriku_app;
GRANT INSERT, UPDATE, DELETE ON TABLE public.industry_qualification_requirements, public.survey_questions, public.survey_options
TO machiriku_app;
GRANT USAGE ON SEQUENCE public.industry_categories_category_id_seq, public.industry_types_industry_type_id_seq,
    public.qualifications_qualification_id_seq, public.user_locations_location_id_seq, public.surveys_survey_id_seq,
    public.survey_questions_question_id_seq, public.survey_options_option_id_seq
TO machiriku_app;

COMMIT;
